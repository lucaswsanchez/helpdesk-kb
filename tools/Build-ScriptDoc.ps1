<#
.SYNOPSIS
    Generates the documentation page of every toolkit script from its comment-based help.

.DESCRIPTION
    Reads each scripts/*.ps1 with Get-Help and the PowerShell parser, and
    writes docs/scripts/<ScriptName>.md with the synopsis, safety facts
    (read-only or not, -WhatIf support, admin rights), description,
    parameters, examples and notes.

    Keeping the help inside the script as the single source of truth means
    Get-Help and the website always say the same thing. Use -Check in CI to
    fail when a page is out of date.

.PARAMETER Check
    Do not write files; exit with code 1 if any generated page differs from the committed one.

.EXAMPLE
    ./tools/Build-ScriptDoc.ps1
    Regenerates all script pages.

.EXAMPLE
    ./tools/Build-ScriptDoc.ps1 -Check
    Verifies the committed pages are up to date.
#>
[CmdletBinding()]
param(
    [switch]$Check
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$scriptDir = Join-Path $repoRoot 'scripts'
$docDir = Join-Path $repoRoot 'docs\scripts'
$repoUrl = 'https://github.com/lucaswsanchez/helpdesk-kb/blob/main'

# Facts that are not visible in the help text but matter to a technician.
$readOnly = @{
    'Get-SystemDiagnostics'    = $true
    'Test-Connectivity'        = $true
    'Export-InstalledSoftware' = $true
    'Get-InactiveAccount'      = $true
    'Clear-TempFiles'          = $false
    'New-BulkADUser'           = $false
    'Reset-PrintSpooler'       = $false
}

function Get-HelpText {
    param([object]$Value)
    if ($null -eq $Value) { return '' }
    (@($Value) | ForEach-Object { if ($_.PSObject.Properties['Text']) { $_.Text } else { [string]$_ } }) -join "`n"
}

function ConvertTo-MarkdownParagraph {
    # Get-Help keeps the original line breaks; join wrapped lines but keep
    # blank lines and indented lists.
    param([string]$Text)
    $lines = ($Text -replace "`r", '') -split "`n"
    $out = New-Object System.Collections.Generic.List[string]
    $buffer = ''
    foreach ($line in $lines) {
        $trimmed = $line.Trim()
        if ($trimmed -eq '') {
            if ($buffer) { $out.Add($buffer); $buffer = '' }
            $out.Add('')
        } elseif ($trimmed -match '^(-|\d+\.)\s') {
            if ($buffer) { $out.Add($buffer); $buffer = '' }
            $buffer = $trimmed
        } elseif ($buffer) {
            $buffer = "$buffer $trimmed"
        } else {
            $buffer = $trimmed
        }
    }
    if ($buffer) { $out.Add($buffer) }
    # Lists need a blank line before them in Markdown.
    $result = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $out.Count; $i++) {
        if ($out[$i] -match '^(-|\d+\.)\s' -and $i -gt 0 -and $out[$i - 1] -ne '' -and $out[$i - 1] -notmatch '^(-|\d+\.)\s') {
            $result.Add('')
        }
        $result.Add($out[$i])
    }
    (($result -join "`n") -replace "`n{3,}", "`n`n").Trim()
}

function ConvertTo-ScriptPage {
    param([System.IO.FileInfo]$File)

    $name = $File.BaseName
    $help = Get-Help -Name $File.FullName -Full
    $tokens = $null
    $errors = $null
    $ast = [System.Management.Automation.Language.Parser]::ParseFile($File.FullName, [ref]$tokens, [ref]$errors)

    $binding = $ast.ParamBlock.Attributes | Where-Object { $_.TypeName.Name -eq 'CmdletBinding' }
    $supportsWhatIf = [bool]($binding.NamedArguments | Where-Object { $_.ArgumentName -eq 'SupportsShouldProcess' })
    $text = Get-Content -LiteralPath $File.FullName -Raw
    $needsAdmin = if ($text -match 'Test-IsAdministrator') { 'Yes (except with `-WhatIf`)' }
    elseif ($text -match 'IncludeWindowsTemp') { 'Only with `-IncludeWindowsTemp`' }
    elseif ($text -match 'ActiveDirectory') { 'AD permissions in AD mode; none for simulation/CSV mode' }
    else { 'No' }

    $sb = New-Object System.Text.StringBuilder
    $null = $sb.AppendLine('---')
    $null = $sb.AppendLine("title: $name")
    $null = $sb.AppendLine('---')
    $null = $sb.AppendLine()
    $null = $sb.AppendLine('<!-- Generated by tools/Build-ScriptDoc.ps1 from the script''s comment-based help. Do not edit by hand. -->')
    $null = $sb.AppendLine()
    $null = $sb.AppendLine("# $name")
    $null = $sb.AppendLine()
    $null = $sb.AppendLine((Get-HelpText $help.Synopsis).Trim())
    $null = $sb.AppendLine()
    $null = $sb.AppendLine('| | |')
    $null = $sb.AppendLine('|---|---|')
    $null = $sb.AppendLine("| **Changes the system** | $(if ($readOnly[$name]) { 'No, read-only' } else { 'Yes' }) |")
    $null = $sb.AppendLine("| **Supports ``-WhatIf`` / ``-Confirm``** | $(if ($supportsWhatIf) { 'Yes' } else { 'Not needed (read-only)' }) |")
    $null = $sb.AppendLine("| **Admin rights** | $needsAdmin |")
    $null = $sb.AppendLine('| **PowerShell** | Windows PowerShell 5.1 and PowerShell 7+ |')
    $null = $sb.AppendLine("| **Source** | [scripts/$($File.Name)]($repoUrl/scripts/$($File.Name)) &middot; [tests]($repoUrl/tests/$name.Tests.ps1) |")
    $null = $sb.AppendLine()

    $null = $sb.AppendLine('## Description')
    $null = $sb.AppendLine()
    $null = $sb.AppendLine((ConvertTo-MarkdownParagraph (Get-HelpText $help.Description)))
    $null = $sb.AppendLine()

    $null = $sb.AppendLine('## Parameters')
    $null = $sb.AppendLine()
    $null = $sb.AppendLine('| Parameter | Type | Default | Description |')
    $null = $sb.AppendLine('|---|---|---|---|')
    foreach ($p in $ast.ParamBlock.Parameters) {
        $pName = $p.Name.VariablePath.UserPath
        $type = $p.StaticType.Name -replace '^SwitchParameter$', 'switch'
        $mandatory = [bool]($p.Attributes | Where-Object { $_.TypeName.Name -eq 'Parameter' -and $_.NamedArguments.ArgumentName -contains 'Mandatory' })
        $default = if ($mandatory) { '*required*' }
        elseif ($p.DefaultValue) { '`' + (($p.DefaultValue.Extent.Text -replace '\s+', ' ') -replace '\|', '\|') + '`' }
        else { '' }
        $pHelp = $help.Parameters.Parameter | Where-Object Name -EQ $pName
        $desc = ((Get-HelpText $pHelp.Description) -replace '\s+', ' ').Trim() -replace '\|', '\|'
        $null = $sb.AppendLine("| ``-$pName`` | $type | $default | $desc |")
    }
    $null = $sb.AppendLine()

    $null = $sb.AppendLine('## Examples')
    $null = $sb.AppendLine()
    foreach ($ex in @($help.Examples.Example)) {
        $code = ([string]$ex.Code).Trim()
        $remarks = ((Get-HelpText $ex.Remarks) -replace '\s+', ' ').Trim()
        $null = $sb.AppendLine('```powershell')
        $null = $sb.AppendLine($code)
        $null = $sb.AppendLine('```')
        $null = $sb.AppendLine()
        if ($remarks) {
            $null = $sb.AppendLine($remarks)
            $null = $sb.AppendLine()
        }
    }

    $notes = Get-HelpText $help.alertSet.alert
    if ($notes.Trim()) {
        $null = $sb.AppendLine('## Notes')
        $null = $sb.AppendLine()
        $null = $sb.AppendLine((ConvertTo-MarkdownParagraph $notes))
        $null = $sb.AppendLine()
    }

    $null = $sb.AppendLine('!!! tip "Built-in help"')
    $null = $sb.AppendLine("    Everything on this page is also available offline: ``Get-Help .\$($File.Name) -Full``.")
    ($sb.ToString() -replace "`r", '').TrimEnd() + "`n"
}

$stale = New-Object System.Collections.Generic.List[string]
foreach ($file in Get-ChildItem -Path $scriptDir -Filter *.ps1 | Sort-Object Name) {
    $content = ConvertTo-ScriptPage -File $file
    $target = Join-Path $docDir "$($file.BaseName).md"
    $current = if (Test-Path $target) { (Get-Content -LiteralPath $target -Raw) -replace "`r", '' } else { '' }

    if ($Check) {
        if ($current -ne $content) { $stale.Add($file.BaseName) }
    } else {
        [System.IO.File]::WriteAllText($target, $content, [System.Text.UTF8Encoding]::new($false))
        Write-Host "Wrote docs/scripts/$($file.BaseName).md"
    }
}

if ($Check) {
    if ($stale.Count -gt 0) {
        Write-Host "Out-of-date script pages: $($stale -join ', '). Run ./tools/Build-ScriptDoc.ps1" -ForegroundColor Red
        exit 1
    }
    Write-Host 'Script documentation pages are up to date.' -ForegroundColor Green
}
