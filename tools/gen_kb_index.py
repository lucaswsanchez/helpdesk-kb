"""Generate docs/kb/index.md from the YAML front matter of every KB article.

Usage:
    python tools/gen_kb_index.py          # rewrite docs/kb/index.md
    python tools/gen_kb_index.py --check  # exit 1 if the index is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
KB_DIR = ROOT / "docs" / "kb"
INDEX = KB_DIR / "index.md"

# Display order and anchor for each category (anchors are linked from the home page).
CATEGORIES: dict[str, str] = {
    "Accounts & Identity": "accounts-identity",
    "Microsoft 365": "microsoft-365",
    "Network": "network",
    "Hardware & Printing": "hardware-printing",
    "Software": "software",
    "Security": "security",
    "Onboarding & Offboarding": "onboarding-offboarding",
}


def read_front_matter(path: Path) -> dict:
    """Return the YAML front matter of a Markdown file (empty dict if none)."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    try:
        _, block, _ = text.split("---", 2)
    except ValueError:
        return {}
    return yaml.safe_load(block) or {}


def article_paths() -> list[Path]:
    return sorted(KB_DIR.glob("kb-*.md"))


def render_index(articles: list[tuple[Path, dict]]) -> str:
    l1 = sum(1 for _, m in articles if m.get("level") == "L1")
    l2 = sum(1 for _, m in articles if m.get("level") == "L2")
    lines = [
        "---",
        "title: Knowledge Base",
        "hide:",
        "  - toc",
        "---",
        "",
        "<!-- Generated by tools/gen_kb_index.py from article front matter. Do not edit by hand. -->",
        "",
        "# Knowledge Base",
        "",
        f"**{len(articles)} articles** ({l1} L1 self-service / first-line, {l2} L2 technician). "
        "Use the search bar for error messages, or browse by category below.",
        "",
        "!!! tip \"Support levels\"",
        "    **L1** articles can be followed by the user or a first-line technician. "
        "**L2** articles need admin rights or a specialist team; the user should open a ticket.",
        "",
        '<div class="table-filters" data-columns="Level" data-scope="all" aria-label="Filter articles by support level"></div>',
        "",
    ]
    for category, anchor in CATEGORIES.items():
        rows = [(p, m) for p, m in articles if m.get("category") == category]
        if not rows:
            continue
        lines += [
            f"## {category} {{#{anchor}}}",
            "",
            '<div class="kb-table" markdown>',
            "",
            "| ID | Article | Level | Est. time |",
            "|---|---|---|---|",
        ]
        for path, meta in rows:
            lines.append(
                f"| {meta['id']} | [{meta['title']}]({path.name}) | "
                f'<span class="badge badge--{str(meta["level"]).lower()}">{meta["level"]}</span> | '
                f"{meta.get('estimated_time', '')} |"
            )
        lines += ["", "</div>", ""]
    lines += [
        "---",
        "",
        "Writing a new article? Start from the [KB article template](article-template.md).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the index is out of date")
    args = parser.parse_args(argv)

    articles = [(p, read_front_matter(p)) for p in article_paths()]
    articles.sort(key=lambda item: str(item[1].get("id", "")))
    content = render_index(articles)

    if args.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current.replace("\r\n", "\n") != content:
            print("docs/kb/index.md is out of date. Run: python tools/gen_kb_index.py", file=sys.stderr)
            return 1
        print(f"KB index is up to date ({len(articles)} articles).")
        return 0

    INDEX.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {INDEX.relative_to(ROOT)} with {len(articles)} articles.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
